#include <stdio.h>
#include <string.h>

int main() {
    char name[3][20];
    float m[3], p[3], c[3]; // คะแนน Math, Phy, Chem ของ 3 คน
    float sum_m = 0, sum_p = 0, sum_c = 0;

    // 1. รับข้อมูล 3 คน
    for (int i = 0; i < 3; i++) {
        printf("ชื่อ นักเรียนคนที่ %d: ", i + 1);
        scanf("%s", name[i]);
        printf("คะแนน Math Phy Chem: ");
        scanf("%f %f %f", &m[i], &p[i], &c[i]);
        
        // คำนวณผลรวมคะแนนเพื่อหาค่าเฉลี่ย
        sum_m += m[i];
        sum_p += p[i];
        sum_c += c[i];
    }

    // 2. แสดงผลตาราง
    printf("\n=========================================================\n");
    // หัวตาราง: กำหนดระยะความกว้างให้ตรงกับข้อมูลบรรทัดล่าง
    printf("%-20s %-10s %-10s %-10s\n", "Student (length)", "Math", "Phy", "Chem");
    printf("=========================================================\n");

    // วนลูปพิมพ์ข้อมูลนักเรียนแต่ละคน
    for (int i = 0; i < 3; i++) {
        char name_with_len[30];
        // รวมชื่อและความยาวสตรีง เช่น "Apichaya (8)"
        sprintf(name_with_len, "%s (%lu)", name[i], strlen(name[i]));

        // %-20s = ชิดซ้ายเว้น 20 ช่อง | %-10.2f = ชิดซ้ายเว้น 10 ช่อง (ทศนิยม 2 ตำแหน่ง)
        printf("%-20s %-10.2f %-10.2f %-10.2f\n", name_with_len, m[i], p[i], c[i]);
    }

    // 3. แสดงแถบสรุปค่าเฉลี่ย
    printf("=========================================================\n");
    printf("%-20s %-10.2f %-10.2f %-10.2f\n", "Subject average", sum_m / 3.0, sum_p / 3.0, sum_c / 3.0);
    printf("=========================================================\n");

    return 0;
}
